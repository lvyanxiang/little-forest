const fs = require('node:fs')
const path = require('node:path')

const root = path.resolve(__dirname, '..')

function readApiBase(environment) {
  const filename = `.env.${environment}`
  const source = fs.existsSync(path.join(root, filename)) ? filename : `${filename}.example`
  const contents = fs.readFileSync(path.join(root, source), 'utf8')
  const entries = contents.split(/\r?\n/).filter(line => /^\s*(?:export\s+)?API_BASE\s*=/.test(line))
  if (entries.length !== 1) throw new Error(`${source} 必须配置且只配置一个 API_BASE`)
  const raw = entries[0].replace(/^\s*(?:export\s+)?API_BASE\s*=\s*/, '').trim()
  const quoted = raw.match(/^(['"])(.*?)\1\s*(?:#.*)?$/)
  const value = quoted ? quoted[2] : raw.replace(/\s+#.*$/, '').trim()
  const url = new URL(value)
  if (!['http:', 'https:'].includes(url.protocol) || url.username || url.password || url.search || url.hash || !/^\/api\/?$/.test(url.pathname)) {
    throw new Error(`${source} 的 API_BASE 必须是以 /api 结尾的 HTTP(S) 地址`)
  }
  if (environment === 'production' && (url.protocol !== 'https:' || url.port || url.hostname === 'localhost' || /^[\d.]+$/.test(url.hostname) || url.hostname.includes(':'))) {
    throw new Error(`${source} 的 API_BASE 必须使用无自定义端口的 HTTPS 域名`)
  }
  return value.replace(/\/$/, '')
}

try {
  const development = readApiBase('development')
  const production = readApiBase('production')
  const output = '// Generated by npm run config:env. Edit the .env files instead.\n'
    + `export const DEVELOP_API_BASE = ${JSON.stringify(development)}\n`
    + `export const PRODUCTION_API_BASE = ${JSON.stringify(production)}\n`
  fs.writeFileSync(path.join(root, 'miniprogram/utils/env.generated.ts'), output)
  console.log('已生成小程序开发及生产 API 配置')
} catch (error) {
  console.error(`小程序 API 配置生成失败：${error.message}`)
  process.exitCode = 1
}
